#!/usr/bin/env python3
"""Replay the characterisation sweep's final populations and measure what the sweep did not keep. Run 48.

The sweep (runs 42 to 44) stored every arm's final population, 20 seeds by 256 genomes, in its condition
checkpoints. Evolution never needs to be repeated to answer the questions it left open, because every quantity
below is a property of those final weights in a stated world. This script re-evaluates them on the GPU that
evolved them and writes one compact file per job. It changes nothing in the sweep's output.

### Why each job exists

    own     every arm in the world its stored numbers came from. Reproduces the stored rows BIT FOR BIT
            before measuring anything new, which proves the key reconstruction, the code and the device all
            match the sweep. Then adds per-genome rows for the arms that stored only population means, and
            the engagement, lifetime and trajectory data below. 103 jobs
    real    the third arm's final weights against the REAL predator at the same condition. The sweep only
            ever measured that arm where the predator cannot damage, so its every comparison was invalid
            (DEV-037). 23 jobs
    nullp   the null baseline's final weights against the predator at each predator-only setting. The sweep
            skipped those because the null's evolution never meets a predator, but its EVALUATION does
            (DEV-036). The null lineage's weights do not depend on predator settings, so the baseline's
            final populations are the null for every such setting. 22 jobs

Excluded throughout: conditions where the predator out-sees the prey (D-074). Counted once: configurations
the plan repeated (DEV-035).

### What is measured, per genome

    rows        the sweep's own accumulator pass, every accumulator plus the three tier-one outcomes, one
                episode, the identical program the sweep ran
    engagement  over `--episodes` episodes: engagements, and how each ended. An engagement is a maximal run of
                ticks on which the prey is engaged, read from the environment's OWN `engaged_ticks` counter
                tick by tick, so the definition cannot drift from the one every descriptor uses
    prey        per prey per episode: ticks alive, death tick, both death flags, score, spawn relaxation
    trajectory  for a fixed sample of genomes per seed, the renderer's per-tick record without the food and
                target grids, which are large and can be regenerated by replaying the stored key. It comes
                from a separate compiled program over 16 genomes, and a last-bit difference between programs
                can flip a nearly tied action (DEV-038), so `traj_diverged` marks each sampled genome whose
                trajectory does not end the way the counted episode 0 did. D-080

An engagement ends in exactly one of four ways, decided before any of this was run:

    captured     the prey died with the predation flag set on a tick inside the engagement
    died_other   the prey died inside the engagement without the predation flag (starvation)
    censored     the engagement was still running on the last tick and the prey was alive
    escaped      the engagement ended and the prey was alive on the following tick

So `escaped + captured + died_other + censored == engagements` for every genome, and the engaged ticks summed
over all engagements equal the environment's `engaged_ticks` total. Both hold by construction and are
therefore NOT asserted; the independent check is `sweep_mismatch`, see `engagement_counts`.

### Keys

Every seed's key is the fixed chain the sweep used: `key(seed + 2)`, split three ways once per generation, then
split once after the loop for the null's evaluation. So the last sampled generation's key (`ka`) and the
evaluation key (`ke`) are recomputed exactly. `own` uses the key the stored row was made with; `real` and
`nullp` use `ke`, as the sweep's null evaluation did. Episode 0 of the engagement pass uses the same per-genome
key as the rows, and is required to reproduce them; later episodes fold the episode index into that key.

Usage, on the A6000, from the derived repository, after `. scripts/a6000/env.sh`:
    uv run python scripts/measure/replay_final.py runs/sweep runs/replay
    uv run python scripts/measure/replay_final.py runs/sweep runs/replay --plan-only
Options: --jobs REGEX, --seeds N, --episodes N, --traj-genomes N, --allow-drift, --allow-cpu.
Resumable: run the same command again; finished jobs are skipped after their schema is checked.
"""

