# ----------------------------------------------------------------------------------------------- the plan --
def excluded(axis: str, level) -> bool:
    """D-074: the predator may not out-see the prey. Derived from the prey radius, not transcribed."""
    return axis == "r_pred" and level is not None and int(level) > DEFAULT.r


@dataclasses.dataclass(frozen=True)
class Job:
    kind: str  # own | real | nullp
    source_tag: str  # the checkpoint whose final populations are evaluated
    arm: str  # the arm that evolved them
    axis: str
    level: object
    world: str  # "own" or "predator": the evaluation world's run configuration
    key_kind: str  # "ka" or "ke"

    @property
    def name(self) -> str:
        return f"{self.kind}__{sweep.condition_tag(self.arm, self.axis, self.level)}"


def world_params(job: Job):
    """The evaluation world. `own` is where the stored numbers came from: the arm's own world for an evolving
    arm, the predator world (naive_eval) for the null. `predator` is naive_eval at the job's axis level, which
    is the scripted predator's configuration with that one replacement (asserted in the tests)."""
    if job.world == "own" and job.arm != "null":
        return sweep.params_for(job.arm, job.axis, job.level)
    base = sweep.BY_NAME["naive_eval"].params
    p = base if job.axis == "baseline" else dataclasses.replace(base, **{job.axis: job.level})
    sweep.check_invariants(p)
    return p


def plan() -> list[Job]:
    jobs: list[Job] = []
    seen: set[str] = set()
    for arm in ("treatment", "third", "null"):
        for axis, level in sweep.conditions(arm):
            if excluded(axis, level):
                continue
            h = loop.config_hash(sweep.params_for(arm, axis, level))
            if (arm, h) in seen:  # DEV-035: the third arm repeats its baseline three times
                continue
            seen.add((arm, h))
            tag = sweep.condition_tag(arm, axis, level)
            jobs.append(Job("own", tag, arm, axis, level, "own", "ke" if arm == "null" else "ka"))
            if arm == "third":
                jobs.append(Job("real", tag, arm, axis, level, "predator", "ke"))
    null_base = sweep.condition_tag("null", "baseline", None)
    for axis, level in sweep.conditions("treatment"):
        if axis in sweep.PREDATOR_ONLY and not excluded(axis, level):
            jobs.append(Job("nullp", null_base, "null", axis, level, "predator", "ke"))
    return jobs


# ---------------------------------------------------------------------------------------------- the keys --
def seed_keys(seed: int, n_generations: int):
    """(ka of the last generation, ke): the sweep's key chain, recomputed. No simulation is needed."""
    key = jax.random.key(seed + 2)
    ka = None
    for _ in range(n_generations):
        key, _kg, ka = jax.random.split(key, 3)
    key, ke = jax.random.split(key)
    return ka, ke


# ----------------------------------------------------------------------------------------- the world ----
def build_static(p, seed: int, eval_p):
    """The arm's layout from `p`, then the evaluation world from `eval_p` by the same three calls the sweep
    uses, asserting the obstacle layout is shared exactly as the sweep asserts it."""
    ob = grid.make_obstacle_grid(jax.random.key(seed), p.h, p.w, p.obstacle_density)
    ob_e = grid.make_obstacle_grid(jax.random.key(seed), eval_p.h, eval_p.w, eval_p.obstacle_density)
    assert bool(jnp.array_equal(ob_e, ob)), "evaluation layout differs from the arm's"
    fs, ts, _ = resources.place_sources(jax.random.key(seed), ob_e, eval_p)
    return E.StaticEnv(
        obstacles=ob_e, vis_table=build_vis_table(ob_e, required_radius(eval_p)), food_src=fs, target_src=ts
    )


def make_engagement_pass(unflatten, params):
    """One episode per genome through the SAME `reset` and `tick` the sweep uses, emitting per tick the running
    `engaged_ticks` and the alive mask, so engagement runs are read from the environment's own definition.

    **The world is an ARGUMENT, not a closed-over constant.** The sweep's own pass bakes each seed's layout into
    its program, so it compiles once per seed; that is kept for the reproduction pass, which must be the
    identical program to reproduce bit for bit. This pass is cross-checked instead, and taking the world as an
    argument lets one compiled program serve all twenty seeds of a job."""

    def one(vec, k, static):
        k_reset, k_draws = jax.random.split(k)
        weights = unflatten(vec)
        entropy = ent.PRNGSource(k_draws)
        state = E.reset(ent.PRNGSource(k_reset), static, params)
        acc = E.zero_accumulators(params.k)

        def body(carry, _):
            st, ac, t = carry
            st, ac, _rec = E.tick(st, ac, weights, static, entropy, t, params)
            return (st, ac, t + 1), (ac.engaged_ticks, st.prey_alive)

        (st, ac, _), (eng_running, alive_after) = jax.lax.scan(
            body, (state, acc, jnp.int32(0)), None, length=params.t_horizon
        )
        row = jnp.concatenate(
            [
                jnp.stack([jnp.mean(getattr(ac, f).astype(jnp.float32)) for f in sweep.ACC_FIELDS]),
                jnp.stack(
                    [
                        jnp.mean(st.prey_died_predated.astype(jnp.float32)),
                        jnp.mean(st.prey_died_starving.astype(jnp.float32)),
                        jnp.mean(st.prey_alive.astype(jnp.float32)),
                    ]
                ),
            ]
        )
        prey = jnp.stack(
            [
                ac.alive_ticks.astype(jnp.int32),
                st.prey_death_step,
                st.prey_died_predated.astype(jnp.int32),
                st.prey_died_starving.astype(jnp.int32),
                st.prey_alive.astype(jnp.int32),
                st.prey_score.astype(jnp.int32),
            ]
        )
        return row, eng_running, prey, st.spawn_relax_level

    return jax.jit(jax.vmap(one, in_axes=(0, 0, None)))


def make_trajectory_pass(unflatten, params):
    """The renderer's per-tick record for a sample of genomes, world as an argument for the same reason."""

    def one(vec, k, static):
        k_reset, k_draws = jax.random.split(k)
        _st, _acc, ys = E.run_episode(
            k_reset, unflatten(vec), static, ent.PRNGSource(k_draws), params, record=True
        )
        return tuple(getattr(ys, f) for f in TRAJ_FIELDS)

    return jax.jit(jax.vmap(one, in_axes=(0, 0, None)))


# ------------------------------------------------------------------------------------ engagement runs ----
def engagement_counts(eng_running: np.ndarray, prey: np.ndarray) -> np.ndarray:
    """(G, T, k) running engaged_ticks and (G, 6, k) prey facts -> (G, len(ENGAGEMENT_FIELDS)) counts.

    Asserts the two accounting identities. Pure numpy, so it is unit-tested on hand-built arrays."""
    eng_running = np.asarray(eng_running, np.int64)
    G, T, k = eng_running.shape
    inc = np.diff(np.concatenate([np.zeros((G, 1, k), np.int64), eng_running], axis=1), axis=1)
    assert np.isin(inc, (0, 1)).all(), "engaged_ticks moved by something other than 0 or 1 in a tick"
    e = inc.astype(np.int8)
    d = np.diff(
        np.concatenate([np.zeros((G, 1, k), np.int8), e, np.zeros((G, 1, k), np.int8)], axis=1), axis=1
    )
    sg, st, sp = np.nonzero(d == 1)
    eg, et, ep = np.nonzero(d == -1)
    so = np.lexsort((st, sp, sg))
    eo = np.lexsort((et, ep, eg))
    sg, st, sp = sg[so], st[so], sp[so]
    eg, et, ep = eg[eo], et[eo] - 1, ep[eo]
    assert np.array_equal(sg, eg) and np.array_equal(sp, ep), "engagement starts and ends do not pair"

    death = prey[:, 1, :]
    predated = prey[:, 2, :].astype(bool)
    alive_end = prey[:, 4, :].astype(bool)
    ds = death[sg, sp]
    died_in = (ds >= st) & (ds <= et) & (ds >= 0)
    captured = died_in & predated[sg, sp]
    died_other = died_in & ~predated[sg, sp]
    censored = ~died_in & (et == T - 1) & alive_end[sg, sp]
    escaped = ~died_in & ~censored

    out = np.zeros((G, len(ENGAGEMENT_FIELDS)), np.int64)
    for j, mask in enumerate((np.ones_like(captured), escaped, captured, died_other, censored)):
        np.add.at(out[:, j], sg, mask.astype(np.int64))
    np.add.at(out[:, 5], sg, (et - st + 1))
    in_any = np.zeros((G, k), bool)
    in_any[sg[captured], sp[captured]] = True
    out[:, 6] = (predated & ~in_any).sum(axis=1)
    # **No identity is asserted here, and that is deliberate.** The four outcomes partition the engagements and
    # the run lengths sum to the counter's last value BY CONSTRUCTION: both are computed from the same counter,
    # so an assertion of either can never fail, and a check that cannot fail manufactures confidence. The
    # independent check is `sweep_mismatch`, against the sweep's own accumulator from a separate program.
    return out


def sweep_mismatch(eng_ep0: np.ndarray, rows: np.ndarray, cols: list[str], k: int) -> int:
    """Genomes whose engaged ticks, counted here from the per-tick record, disagree with the sweep's own
    `engaged_ticks` accumulator from its separate program on the same episode. Zero when the two passes saw
    the same episode; anything else means the engagement data describes a different trajectory."""
    ours = eng_ep0[:, ENGAGEMENT_FIELDS.index("engaged_ticks")].astype(np.float64)
    theirs = rows[:, cols.index("engaged_ticks")].astype(np.float64) * k
    return int(np.sum(np.abs(ours - theirs) > 1e-3))


def traj_mismatch(traj_alive: np.ndarray, prey_ep0: np.ndarray, idx: np.ndarray) -> np.ndarray:
    """Per sampled genome, True where the trajectory pass's final alive mask differs from the engagement pass's
    episode 0 for the same genome and key. The two are separate compiled programs over different batch sizes, so
    a last-bit difference can flip a nearly tied action and send the episode elsewhere (DEV-038). True marks a
    trajectory that does not describe the counted episode. D-080"""
    final_alive = np.asarray(traj_alive)[:, -1, :].astype(bool)
    counted = np.asarray(prey_ep0)[np.asarray(idx), 4, :].astype(bool)
    return ~np.all(final_alive == counted, axis=1)


# ------------------------------------------------------------------------------------------ one job -----
def run_job(
    job: Job,
    ckpt: dict,
    out_path: pathlib.Path,
    *,
    n_seeds: int,
    episodes: int,
    traj_genomes: int,
    allow_drift: bool,
    log,
) -> dict:
    p_arm = sweep.params_for(
        job.arm, job.axis if job.kind != "nullp" else "baseline", job.level if job.kind != "nullp" else None
    )
    eval_p = world_params(job)
    pops = ckpt["final_pop"]
    n_gen = int(ckpt["n_generations"])
    cols = [str(c) for c in ckpt["acc_fields"]]
    assert tuple(cols) == sweep.EXPECTED_SCHEMA, "checkpoint schema differs from the code's"
    G = int(pops.shape[1])

    rows_all, eng_all, prey_all, relax_all, repro, cross = [], [], [], [], [], []
    traj_all, traj_idx_all, traj_bad_all = {f: [] for f in TRAJ_FIELDS}, [], []
    t_job = time.time()
    # One unflattener and one compiled engagement and trajectory program per job: the network's structure does
    # not depend on the seed, only its initial values do, and the world is passed in.
    job_unflatten = genome.unflattener(net.init_params(jax.random.key(0), p_arm))
    eng_pass = make_engagement_pass(job_unflatten, eval_p)
    traj_pass = make_trajectory_pass(job_unflatten, eval_p) if traj_genomes else None
    for s in range(n_seeds):
        t0 = time.time()
        template = net.init_params(jax.random.key(s), p_arm)
        unflatten = genome.unflattener(template)
        static = build_static(p_arm, s, eval_p)
        ka, ke = seed_keys(s, n_gen)
        key = ka if job.key_kind == "ka" else ke
        pop = jnp.asarray(pops[s])

        acc_pass = sweep.make_accumulator_pass(unflatten, static, eval_p)
        rows = acc_pass.all(key, pop)
        rec = {"seed": s}
        if job.kind == "own":
            stored = (
                np.asarray(ckpt["naive_acc"][s])
                if job.arm == "null"
                else np.asarray(ckpt["sample_acc"][s, -1])
            )
            mean = rows.mean(axis=0).astype(np.float32)
            rec["exact"] = bool(np.array_equal(mean, stored))
            rec["max_abs_diff"] = float(np.max(np.abs(mean.astype(np.float64) - stored)))
            if job.arm == "null":
                rec["per_genome_exact"] = bool(
                    np.array_equal(rows.astype(np.float32), np.asarray(ckpt["naive_acc_per_genome"][s]))
                )
            if not rec["exact"] and not allow_drift:
                raise SystemExit(
                    f"{job.name} seed {s}: the replay does not reproduce the stored row bit for bit (max abs "
                    f"diff {rec['max_abs_diff']:.3g}). The key chain, the code or the device differs from the "
                    "sweep's, so nothing new would be comparable. Stopping. --allow-drift overrides, and the "
                    "difference is then recorded per seed."
                )
        repro.append(rec)

        del acc_pass  # its program is this seed's alone; dropping it lets the cache entry go. DEV-029
        keys = jax.random.split(key, p_arm.p_pop)
        eng_eps, prey_eps, relax_eps = [], [], []
        for e in range(episodes):
            ek = keys if e == 0 else jax.vmap(lambda kk, e=e: jax.random.fold_in(kk, e))(keys)
            row_e, running, prey, relax = eng_pass(pop, ek, static)
            running, prey = np.asarray(running), np.asarray(prey)
            counts = engagement_counts(running, prey)
            if e == 0:
                row_e = np.asarray(row_e)
                bad = sweep_mismatch(counts, rows, cols, eval_p.k)
                cross.append(
                    {
                        "seed": s,
                        "exact": bool(np.array_equal(row_e, rows)),
                        "max_abs_diff": float(np.max(np.abs(row_e.astype(np.float64) - rows))),
                        "engaged_ticks_mismatched_genomes": bad,
                    }
                )
                if bad and not allow_drift:
                    raise SystemExit(
                        f"{job.name} seed {s}: the engagement pass disagrees with the sweep's own engaged_ticks "
                        f"on {bad} genomes, so it replayed a different episode. Stopping. --allow-drift overrides."
                    )
            eng_eps.append(counts)
            prey_eps.append(prey)
            relax_eps.append(np.asarray(relax))
        eng_all.append(np.stack(eng_eps, axis=1))  # (G, episodes, fields)
        prey_all.append(np.stack(prey_eps, axis=1).astype(np.int16))  # (G, episodes, 6, k)
        relax_all.append(np.stack(relax_eps, axis=1).astype(np.int8))
        rows_all.append(rows.astype(np.float32))

        n_traj_bad = 0
        if traj_genomes:
            idx = np.sort(np.random.default_rng(s).choice(G, size=min(traj_genomes, G), replace=False))
            tr = traj_pass(pop[idx], keys[idx], static)
            for f, a in zip(TRAJ_FIELDS, tr, strict=True):
                traj_all[f].append(
                    np.asarray(a).astype(np.int8 if f.endswith("pos") or f.startswith("action") else np.bool_)
                )
            bad_traj = traj_mismatch(tr[TRAJ_FIELDS.index("prey_alive")], prey_eps[0], idx)
            n_traj_bad = int(bad_traj.sum())
            if n_traj_bad and not allow_drift:
                raise SystemExit(
                    f"{job.name} seed {s}: the trajectory pass ended differently from the counted episode on "
                    f"{n_traj_bad} of {idx.size} sampled genomes. Stopping. --allow-drift overrides, and the "
                    "divergence is then recorded per genome in traj_diverged."
                )
            traj_bad_all.append(bad_traj)
            traj_idx_all.append(idx)
        gc.collect()
        verdict = ""
        if "exact" in rec:
            verdict = (
                ", reproduction exact" if rec["exact"] else f", reproduction DRIFT {rec['max_abs_diff']:.2g}"
            )
        if n_traj_bad:
            verdict += f", trajectory diverged on {n_traj_bad}"
        log(f"  {job.name} seed {s}: {time.time() - t0:.1f} s, host RSS {sweep.rss_mb():.0f} MB{verdict}")

    out = {
        "schema_version": np.int32(SCHEMA_VERSION),
        "job": np.array(job.name),
        "kind": np.array(job.kind),
        "arm": np.array(job.arm),
        "axis": np.array(job.axis),
        "level": np.array(str(job.level)),
        "source_tag": np.array(job.source_tag),
        "world": np.array(job.world),
        "key_kind": np.array(job.key_kind),
        "eval_config_hash": np.array(loop.config_hash(eval_p)),
        "source_code_commit": np.array(str(ckpt["code_commit"])),
        "acc_fields": np.array(cols),
        "engagement_fields": np.array(ENGAGEMENT_FIELDS),
        "prey_fields": np.array(PREY_FIELDS),
        "episodes": np.int32(episodes),
        "n_seeds": np.int32(n_seeds),
        "rows": np.stack(rows_all),
        "engagement": np.stack(eng_all).astype(np.int32),
        "prey": np.stack(prey_all),
        "spawn_relax": np.stack(relax_all),
        "reproduction": np.array(json.dumps(repro)),
        "cross_check": np.array(json.dumps(cross)),
        "wall_seconds": np.float32(time.time() - t_job),
        "device": np.array(jax.devices()[0].device_kind),
        "jax_version": np.array(jax.__version__),
    }
    if traj_genomes:
        out["traj_genome_index"] = np.stack(traj_idx_all)
        out["traj_diverged"] = np.stack(traj_bad_all)
        for f in TRAJ_FIELDS:
            out["traj_" + f] = np.stack(traj_all[f])
    tmp = out_path.with_name("." + out_path.name)
    np.savez_compressed(tmp, **out)
    tmp.replace(out_path)
    del eng_pass, traj_pass
    jax.clear_caches()  # once per job, as the sweep does once per condition. DEV-029
    gc.collect()
    return {"job": job.name, "wall": float(out["wall_seconds"]), "repro": repro, "cross": cross}


def output_ok(path: pathlib.Path) -> bool:
    try:
        with np.load(path, allow_pickle=False) as d:
            return int(d["schema_version"]) == SCHEMA_VERSION
    except Exception:  # noqa: BLE001  a damaged or foreign file is not a finished job
        return False


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="replay_final.py", description=__doc__.split("\n")[0])
    ap.add_argument("sweep_dir", type=pathlib.Path)
    ap.add_argument("out_dir", type=pathlib.Path)
    ap.add_argument("--plan-only", action="store_true")
    ap.add_argument("--jobs", default=None, help="regex over job names")
    ap.add_argument("--seeds", type=int, default=None, help="first N seeds only (default: all)")
    ap.add_argument("--episodes", type=int, default=DEFAULT_EPISODES)
    ap.add_argument("--traj-genomes", type=int, default=DEFAULT_TRAJ_GENOMES)
    ap.add_argument("--allow-drift", action="store_true")
    ap.add_argument("--allow-cpu", action="store_true", help="tests and laptop rehearsal only")
    a = ap.parse_args(argv)

    import re

    jobs = plan()
    if a.jobs:
        jobs = [j for j in jobs if re.search(a.jobs, j.name)]
    kinds = {k: sum(j.kind == k for j in jobs) for k in ("own", "real", "nullp")}
    print(f"plan: {len(jobs)} jobs {kinds}; excluded by D-074: r_pred above {DEFAULT.r}")
    if a.plan_only:
        for j in jobs:
            print(f"  {j.name:<52s} from {j.source_tag:<36s} world={j.world:<8s} key={j.key_kind}")
        return 0

    dev = jax.devices()[0]
    if dev.platform != "gpu" and not a.allow_cpu:
        raise SystemExit(
            f"JAX is on the {dev.platform}; the replay must run on the GPU that evolved the weights"
        )
    missing = sorted({j.source_tag for j in jobs if not (a.sweep_dir / f"{j.source_tag}.npz").exists()})
    if missing:
        raise SystemExit(
            f"missing checkpoints in {a.sweep_dir}: {missing[:5]}{' ...' if len(missing) > 5 else ''}"
        )
    a.out_dir.mkdir(parents=True, exist_ok=True)
    log_f = open(a.out_dir / "replay.log", "a", encoding="utf-8")  # noqa: SIM115

    def log(msg):
        line = f"{time.strftime('%Y-%m-%d %H:%M:%S')} {msg}"
        print(line, flush=True)
        log_f.write(line + "\n")
        log_f.flush()

    script_sha = hashlib.sha256(pathlib.Path(__file__).read_bytes()).hexdigest()
    log(f"start: {len(jobs)} jobs on {dev.device_kind}, jax {jax.__version__}, script {script_sha[:12]}")
    jobs.sort(key=lambda j: j.source_tag)  # each 1.4 GB checkpoint is loaded once
    loaded_tag, ckpt, summary, t_all = None, None, [], time.time()
    for i, job in enumerate(jobs, 1):
        out_path = a.out_dir / f"{job.name}.npz"
        if out_path.exists() and output_ok(out_path):
            log(f"[{i}/{len(jobs)}] {job.name}: done earlier, skipped")
            continue
        if job.source_tag != loaded_tag:
            path = a.sweep_dir / f"{job.source_tag}.npz"
            sweep.assert_checkpoint_schema(path)
            with np.load(path, allow_pickle=True) as d:
                ckpt = {
                    k: d[k]
                    for k in (
                        "final_pop",
                        "n_generations",
                        "acc_fields",
                        "code_commit",
                        "sample_acc",
                        "n_seeds",
                        *(("naive_acc", "naive_acc_per_genome") if "naive_acc" in d.files else ()),
                    )
                }
            loaded_tag = job.source_tag
        n_seeds = int(ckpt["n_seeds"]) if a.seeds is None else min(a.seeds, int(ckpt["n_seeds"]))
        log(f"[{i}/{len(jobs)}] {job.name}: {n_seeds} seeds, world {job.world}, key {job.key_kind}")
        res = run_job(
            job,
            ckpt,
            out_path,
            n_seeds=n_seeds,
            episodes=a.episodes,
            traj_genomes=a.traj_genomes,
            allow_drift=a.allow_drift,
            log=log,
        )
        summary.append(res)
        done = len(summary)
        left = sum(1 for j in jobs[i:] if not (a.out_dir / f"{j.name}.npz").exists())
        rate = (time.time() - t_all) / done
        log(f"[{i}/{len(jobs)}] {job.name}: {res['wall']:.0f} s; about {rate * left / 3600:.1f} h left")

    files = sorted(a.out_dir.glob("*__*.npz"))
    with open(a.out_dir / "replay-checksums.sha256", "w", encoding="utf-8") as f:
        for p in files:
            f.write(f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.name}\n")
    (a.out_dir / "REPLAY_DONE").write_text(
        json.dumps(
            {
                "jobs": len(files),
                "script_sha256": script_sha,
                "device": dev.device_kind,
                "finished": time.strftime("%Y-%m-%d %H:%M:%S"),
            },
            indent=1,
        )
        + "\n"
    )
    log(f"finished: {len(files)} job files, checksums written to replay-checksums.sha256")
    return 0


#: Exit code for a deliberate stop: a refused reproduction, a missing checkpoint, the wrong device. The wrapper
#: restarts after a crash and never after this, because running the same thing again would refuse again.
EXIT_REFUSED = 3


def cli() -> int:
    try:
        return main()
    except SystemExit as e:
        if isinstance(e.code, str):
            print(f"STOPPED: {e.code}", flush=True)
            return EXIT_REFUSED
        raise


if __name__ == "__main__":
    sys.exit(cli())
